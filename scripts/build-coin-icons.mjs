// scripts/build-coin-icons.mjs
// One-shot: copies EVERY CC0 spothq/cryptocurrency-icons colour SVG into public/coins/ and emits
// lib/coin-icons.ts. Run by hand; commit the output; do NOT wire into next build.
//   npm i -D cryptocurrency-icons && node scripts/build-coin-icons.mjs && npm un cryptocurrency-icons
import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'node_modules', 'cryptocurrency-icons', 'svg', 'color');
const dest = join(root, 'public', 'coins');

if (!existsSync(src)) {
  console.error(`Missing ${src} — run: npm i -D cryptocurrency-icons`);
  process.exit(1);
}
mkdirSync(dest, { recursive: true });

// Every icon in the package. Deliberately NOT filtered by COIN_NAMES — the icon set and the name
// map are independent lists, and intersecting them loses icons for unnamed coins that are in the
// universe. This script therefore imports nothing from lib/, so plain `node` runs it.
const files = readdirSync(src).filter((f) => f.endsWith('.svg'));
const have = [];
for (const file of files) {
  copyFileSync(join(src, file), join(dest, file));
  have.push(basename(file, '.svg').toLowerCase());
}
have.sort();

writeFileSync(
  join(root, 'lib', 'coin-icons.ts'),
  `/** GENERATED by scripts/build-coin-icons.mjs — do not edit by hand.
 *  Every lowercase base asset that has a bundled SVG in public/coins/ (the WHOLE CC0 icon set, not a
 *  COIN_NAMES subset). Assets absent from this set render CoinIcon's lettered avatar instead
 *  (Task 13) — the MAJORITY visual on the Markets table: 62% of visible rows, 9 of the top 20. */
export const COIN_ICONS: ReadonlySet<string> = new Set([
${have.map((s) => `  '${s}',`).join('\n')}
]);
`,
);

console.log(`copied ${have.length} icons into public/coins/`);
